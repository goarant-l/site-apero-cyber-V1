<div class="apropos-section">

  <h2>Notre manifeste</h2>
  <p>
    On ne boit pas une Bière de l'Apér'o, on la partage. Nous croyons que le moment sacré de la fin de journée
    mérite mieux qu'un simple rafraîchissement.
    Il mérite une alliance : celle du malt de nos terres, du savoir-faire de nos artisans charcutiers et de la passion de nos crémiers.
  </p>
  <p>
    Bien plus qu'une bière, nous défendons un art de vivre : celui de l'apéritif à la française, où chaque produit a sa planche
    et chaque moment devient un souvenir.
  </p>
  <p>Nous sommes le trait d'union entre la pression et la planche, entre l'amertume et le caractère.</p>

  <h2>Notre histoire</h2>
  <p>
    Tout commence à Pont-de-Buis, au cœur de la vallée de la Douffine.
    Trois amis - un brasseur, un charcutier et un affineur - se retrouvent un soir autour d'une table.
    De cette rencontre naît une idée : créer une bière pensée pour accompagner l'apéritif.
  </p>
  <p>Une bière qui ne domine pas, mais qui dialogue. Une bière qui sublime le fromage, la charcuterie et les moments partagés.</p>

  <h2>Notre concept</h2>
  <p>
    La Bière de l'Apér'o, ce n'est pas seulement une bière. C'est une expérience complète autour du goût et du partage.
  </p>
  <p>
    Nous proposons une sélection de bières artisanales spécialement conçues pour accompagner les meilleurs produits du terroir.
    Chaque dégustation est pensée comme un équilibre entre boisson et nourriture.
  </p>

  <h2>Nos produits</h2>
  <p>Nous mettons à l'honneur les plaisirs simples mais exigeants de l'apéritif à la française :</p>
  <ul class="liste-apero">
    <li>Bières artisanales (Blonde, Ambrée, Blanche)</li>
    <li>Charcuterie traditionnelle (saucisson sec, jambon cru, rosette)</li>
    <li>Fromages affinés (comté, chèvre, fromages de caractère)</li>
    <li>Produits d'accompagnement (pain, condiments, planches apéro)</li>
  </ul>
  <p>Tous nos produits sont sélectionnés avec soin auprès de producteurs locaux afin de garantir qualité, authenticité et goût.</p>

  <h2>L'expérience Apér'o</h2>
  <p>Nous avons imaginé des accords parfaits entre nos bières et nos produits :</p>
  <ul class="liste-apero">
    <li><strong>La Blonde</strong> : idéale avec comté affiné ou saucisson sec</li>
    <li><strong>L'Ambrée</strong> : parfaite avec jambon cru et fromages puissants</li>
    <li><strong>La Blanche</strong> : sublimée par un chèvre frais</li>
  </ul>
  <p>Nous proposons également des coffrets "prêt-à-déguster" pour vivre une expérience apéritive complète.</p>

